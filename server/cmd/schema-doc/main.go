func renderTable(
	output *bytes.Buffer,
	table databaseTable,
	tableValue catalogTable,
	index catalogIndex,
	repoRoot string,
	outputDir string,
) error {
	fmt.Fprintf(output, "<a id=\"%s\"></a>\n\n", tableAnchor(table.Name))
	fmt.Fprintf(output, "## `%s` — %s\n\n", table.Name, tableValue.Title)
	output.WriteString("| 项目 | 说明 |\n| --- | --- |\n")
	fmt.Fprintf(output, "| Schema | %s |\n", inlineCode(table.Schema))
	fmt.Fprintf(output, "| 分类 | %s |\n", escapeTableCell(classificationLabels[tableValue.Kind]))
	fmt.Fprintf(output, "| 用途 | %s |\n", escapeTableCell(tableValue.Purpose))
	fmt.Fprintf(output, "| 明确不负责 | %s |\n", escapeTableCell(tableValue.Boundary))
	fmt.Fprintf(output, "| 生命周期 / 删除语义 | %s |\n", escapeTableCell(tableValue.Lifecycle))
	fmt.Fprintf(output, "| 写入边界 | %s |\n", escapeTableCell(tableValue.WriteBoundary))
	if table.Comment != "" {
		fmt.Fprintf(output, "| 数据库表注释 | %s |\n", escapeTableCell(table.Comment))
	}
	if len(tableValue.SensitiveFields) > 0 {
		fmt.Fprintf(output, "| Catalog 敏感字段 | %s |\n", inlineCodeList(tableValue.SensitiveFields))
	}
	if tableValue.Notes != "" {
		fmt.Fprintf(output, "| 审查备注 | %s |\n", escapeTableCell(tableValue.Notes))
	}
	output.WriteString("\n")

	fieldNotes := make(map[string]string, len(tableValue.FieldNotes))
	for _, note := range tableValue.FieldNotes {
		fieldNotes[note.Name] = note.Note
	}
	sensitive := make(map[string]struct{}, len(tableValue.SensitiveFields))
	for _, name := range tableValue.SensitiveFields {
		sensitive[name] = struct{}{}
	}
	primary := make(map[string]struct{}, len(table.PrimaryKey))
	for _, name := range table.PrimaryKey {
		primary[name] = struct{}{}
	}
	foreignTargets := make(map[string]string)
	for _, foreignKey := range table.ForeignKeys {
		for _, name := range foreignKey.Columns {
			foreignTargets[name] = foreignKey.RefTable
		}
	}

	output.WriteString("### 字段\n\n")
	output.WriteString("| 字段 | PostgreSQL 类型 | Ent 类型 | NULL | 数据库默认值 | 结构属性 | 说明 |\n")
	output.WriteString("| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, column := range table.Columns {
		defaultValue := "—"
		if column.HasDefault {
			defaultValue = inlineCode(column.Default)
		}
		nullable := "非空"
		if column.Nullable {
			nullable = "可空"
		}
		note := fieldNotes[column.Name]
		if note == "" {
			note = index.commonFields[column.Name]
		}
		if note == "" {
			note = column.Comment
		}
		if note == "" {
			note = inferredColumnNote(column.Name, foreignTargets[column.Name])
		}
		fmt.Fprintf(
			output,
			"| %s | %s | %s | %s | %s | %s | %s |\n",
			inlineCode(column.Name),
			inlineCode(column.PostgresType),
			inlineCode(column.LogicalType),
			nullable,
			defaultValue,
			columnTraits(column, primary, sensitive),
			escapeTableCell(note),
		)
	}
	output.WriteString("\n")

	output.WriteString("### 主键\n\n")
	if len(table.PrimaryKey) == 0 {
		output.WriteString("未声明表级主键。\n\n")
	} else {
		fmt.Fprintf(output, "%s\n\n", inlineCodeList(table.PrimaryKey))
	}

	output.WriteString("### 外键\n\n")
	if len(table.ForeignKeys) == 0 {
		output.WriteString("无外键。\n\n")
	} else {
		output.WriteString("| 约束 | 本表字段 | 引用 | ON UPDATE | ON DELETE |\n")
		output.WriteString("| --- | --- | --- | --- | --- |\n")
		for _, foreignKey := range table.ForeignKeys {
			symbol := "未命名"
			if foreignKey.Symbol != "" {
				symbol = foreignKey.Symbol
			}
			reference := inlineCode(foreignKey.RefSchema + "." + foreignKey.RefTable)
			if targetTable, ok := index.tables[foreignKey.RefTable]; ok {
				targetDomain := index.domains[targetTable.Domain]
				reference = fmt.Sprintf(
					"[%s](%s#%s)",
					inlineCode(foreignKey.RefSchema+"."+foreignKey.RefTable),
					targetDomain.File,
					tableAnchor(foreignKey.RefTable),
				)
			}
			fmt.Fprintf(
				output,
				"| %s | %s | %s %s | %s | %s |\n",
				inlineCode(symbol),
				inlineCodeList(foreignKey.Columns),
				reference,
				inlineCodeList(foreignKey.RefColumns),
				referenceAction(foreignKey.OnUpdate),
				referenceAction(foreignKey.OnDelete),
			)
		}
		output.WriteString("\n")
	}

	output.WriteString("### 索引\n\n")
	if len(table.Indexes) == 0 {
		output.WriteString("无额外显式索引；主键和列级唯一性见上文。\n\n")
	} else {
		output.WriteString("| 索引 | 唯一 | 字段 | Predicate |\n")
		output.WriteString("| --- | --- | --- | --- |\n")
		for _, indexValue := range table.Indexes {
			predicate := "—"
			if indexValue.Predicate != "" {
				predicate = inlineCode(indexValue.Predicate)
			}
			fmt.Fprintf(
				output,
				"| %s | %s | %s | %s |\n",
				inlineCode(indexValue.Name),
				yesNo(indexValue.Unique),
				inlineCodeList(indexValue.Columns),
				predicate,
			)
		}
		output.WriteString("\n")
	}

	output.WriteString("### CHECK 约束\n\n")
	if len(table.Checks) == 0 {
		output.WriteString("无表级 CHECK。\n\n")
	} else {
		for _, check := range table.Checks {
			fmt.Fprintf(output, "- %s\n\n", inlineCode(check.Name))
			output.WriteString(fencedCode("sql", check.Expression))
			output.WriteString("\n")
		}
	}

	output.WriteString("### 代码与业务真源\n\n")
	for _, source := range tableSchemaSources(tableValue) {
		target, err := repoRelativeLink(repoRoot, outputDir, source)
		if err != nil {
			return err
		}
		fmt.Fprintf(output, "- [Schema source: `%s`](%s)\n", filepath.Base(source), target)
	}
	references := uniqueStrings(append(append([]string(nil), index.domains[tableValue.Domain].References...), tableValue.References...))
	for _, reference := range references {
		target, err := repoRelativeLink(repoRoot, outputDir, reference)
		if err != nil {
			return err
		}
		fmt.Fprintf(output, "- [%s](%s)\n", referenceLabel(reference), target)
	}
	output.WriteString("\n")
	return nil
}

func inferredColumnNote(name, foreignTarget string) string {
	if foreignTarget != "" {
		return "外键，关联 `" + foreignTarget + "`。"
	}
	switch {
	case strings.HasSuffix(name, "_no"):
		return "业务编号；唯一性和生成规则见索引与领域 usecase。"
	case strings.HasSuffix(name, "_at"):
		return "业务时间点；具体触发语义见表生命周期。"
	case strings.HasSuffix(name, "_by"):
		return "执行该业务动作的管理员标识。"
	case strings.HasSuffix(name, "_snapshot"):
		return "业务发生时冻结的显示快照，不回写上游主数据。"
	case strings.HasSuffix(name, "_hash"):
		return "用于完整性或幂等校验的摘要。"
	default:
		return "业务含义以字段名、表用途、约束和链接的 schema/usecase 为准。"
	}
}

func columnTraits(column databaseColumn, primary, sensitive map[string]struct{}) string {
	values := make([]string, 0, 8)
	if _, ok := primary[column.Name]; ok {
		values = append(values, "主键")
	}
	if column.Increment {
		values = append(values, "identity")
	}
	if column.Unique {
		values = append(values, "列级唯一")
	}
	if _, ok := sensitive[column.Name]; ok {
		values = append(values, "敏感")
	}
	if len(column.Enums) > 0 {
		values = append(values, "枚举 "+strings.Join(column.Enums, " / "))
	}
	if column.Key != "" {
		values = append(values, "key="+column.Key)
	}
	if column.Attr != "" {
		values = append(values, "attr="+column.Attr)
	}
	if column.Collation != "" {
		values = append(values, "collation="+column.Collation)
	}
	if len(values) == 0 {
		return "—"
	}
	return escapeTableCell(strings.Join(values, "；"))
}

func referenceAction(value string) string {
	if strings.TrimSpace(value) == "" {
		return "未显式指定（PostgreSQL 默认 NO ACTION）"
	}
	return inlineCode(value)
}

func yesNo(value bool) string {
	if value {
		return "是"
	}
	return "否"
}

func tableAnchor(name string) string {
	return "table-" + strings.ReplaceAll(strings.ToLower(name), "_", "-")
}

func inlineCode(value string) string {
	return "<code>" + html.EscapeString(value) + "</code>"
}

func inlineCodeList(values []string) string {
	if len(values) == 0 {
		return "—"
	}
	rendered := make([]string, 0, len(values))
	for _, value := range values {
		rendered = append(rendered, inlineCode(value))
	}
	return strings.Join(rendered, ", ")
}

func escapeTableCell(value string) string {
	value = strings.ReplaceAll(value, "\\", "\\\\")
	value = strings.ReplaceAll(value, "|", "\\|")
	value = strings.ReplaceAll(value, "\r\n", "\n")
	value = strings.ReplaceAll(value, "\r", "\n")
	return strings.ReplaceAll(value, "\n", "<br>")
}

func fencedCode(language, value string) string {
	longest := 0
	current := 0
	for _, runeValue := range value {
		if runeValue == '`' {
			current++
			if current > longest {
				longest = current
			}
		} else {
			current = 0
		}
	}
	length := 3
	if longest >= length {
		length = longest + 1
	}
	fence := strings.Repeat("`", length)
	return fence + language + "\n" + strings.TrimSpace(value) + "\n" + fence + "\n"
}

func normalizeMarkdown(value []byte) []byte {
	value = bytes.ReplaceAll(value, []byte("\r\n"), []byte("\n"))
	value = bytes.TrimRight(value, "\n")
	return append(value, '\n')
}

func repoRelativeLink(repoRoot, outputDir, repoRelative string) (string, error) {
	target := filepath.Join(repoRoot, filepath.FromSlash(repoRelative))
	relative, err := filepath.Rel(outputDir, target)
	if err != nil {
		return "", fmt.Errorf("build relative link for %s: %w", repoRelative, err)
	}
	return filepath.ToSlash(relative), nil
}

func referenceLabel(path string) string {
	base := filepath.Base(path)
	return strings.TrimSuffix(base, filepath.Ext(base))
}

func uniqueStrings(values []string) []string {
	seen := make(map[string]struct{}, len(values))
	result := make([]string, 0, len(values))
	for _, value := range values {
		if _, ok := seen[value]; ok {
			continue
		}
		seen[value] = struct{}{}
		result = append(result, value)
	}
	return result
}

func inspectOutputs(outputDir string, expected map[string][]byte) (outputReport, error) {
	report := outputReport{}
	for _, name := range sortedOutputNames(expected) {
		actual, err := os.ReadFile(filepath.Join(outputDir, name))
		switch {
		case errors.Is(err, os.ErrNotExist):
			report.Missing = append(report.Missing, name)
		case err != nil:
			return outputReport{}, fmt.Errorf("read generated output %s: %w", name, err)
		case !bytes.Equal(actual, expected[name]):
			report.Changed = append(report.Changed, name)
		}
	}

	entries, err := os.ReadDir(outputDir)
	if errors.Is(err, os.ErrNotExist) {
		return report, nil
	}
	if err != nil {
		return outputReport{}, fmt.Errorf("read output directory %s: %w", outputDir, err)
	}
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".md" {
			continue
		}
		if _, ok := expected[entry.Name()]; ok {
			continue
		}
		content, err := os.ReadFile(filepath.Join(outputDir, entry.Name()))
		if err != nil {
			return outputReport{}, fmt.Errorf("read unexpected output %s: %w", entry.Name(), err)
		}
		if bytes.HasPrefix(content, []byte(generatedHeader)) {
			report.Stale = append(report.Stale, entry.Name())
		} else {
			report.Unexpected = append(report.Unexpected, entry.Name())
		}
	}
	sort.Strings(report.Stale)
	sort.Strings(report.Unexpected)
	return report, nil
}

func (report outputReport) clean() bool {
	return len(report.Missing) == 0 &&
		len(report.Changed) == 0 &&
		len(report.Stale) == 0 &&
		len(report.Unexpected) == 0
}

func formatOutputReport(report outputReport) string {
	return fmt.Sprintf(
		"missing=%s changed=%s stale=%s unexpected=%s",
		formatStringList(report.Missing),
		formatStringList(report.Changed),
		formatStringList(report.Stale),
		formatStringList(report.Unexpected),
	)
}

func formatStringList(values []string) string {
	if len(values) == 0 {
		return "[]"
	}
	return "[" + strings.Join(values, ", ") + "]"
}

func writeOutputs(outputDir string, outputs map[string][]byte) error {
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return fmt.Errorf("create output directory %s: %w", outputDir, err)
	}
	for _, name := range sortedOutputNames(outputs) {
		path := filepath.Join(outputDir, name)
		current, err := os.ReadFile(path)
		if err == nil && bytes.Equal(current, outputs[name]) {
			continue
		}
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return fmt.Errorf("read existing output %s: %w", path, err)
		}
		if err := writeFileAtomic(path, outputs[name]); err != nil {
			return err
		}
	}
	return nil
}

func writeFileAtomic(path string, content []byte) (resultErr error) {
	file, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return fmt.Errorf("create temporary output for %s: %w", path, err)
	}
	tempPath := file.Name()
	defer func() {
		if removeErr := os.Remove(tempPath); removeErr != nil &&
			!errors.Is(removeErr, os.ErrNotExist) &&
			resultErr == nil {
			resultErr = fmt.Errorf("remove temporary output for %s: %w", path, removeErr)
		}
	}()
	if _, err := file.Write(content); err != nil {
		if closeErr := file.Close(); closeErr != nil {
			return fmt.Errorf(
				"write temporary output for %s: %w (close error: %v)",
				path,
				err,
				closeErr,
			)
		}
		return fmt.Errorf("write temporary output for %s: %w", path, err)
	}
	if err := file.Chmod(0o644); err != nil {
		if closeErr := file.Close(); closeErr != nil {
			return fmt.Errorf(
				"chmod temporary output for %s: %w (close error: %v)",
				path,
				err,
				closeErr,
			)
		}
		return fmt.Errorf("chmod temporary output for %s: %w", path, err)
	}
	if err := file.Close(); err != nil {
		return fmt.Errorf("close temporary output for %s: %w", path, err)
	}
	if err := os.Rename(tempPath, path); err != nil {
		return fmt.Errorf("replace generated output %s: %w", path, err)
	}
	return nil
}

func sortedOutputNames(outputs map[string][]byte) []string {
	names := make([]string, 0, len(outputs))
	for name := range outputs {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
