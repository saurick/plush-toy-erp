type catalog struct {
	Version      int                `json:"version"`
	Description  string             `json:"description"`
	Exclusions   []catalogExclusion `json:"exclusions"`
	Domains      []catalogDomain    `json:"domains"`
	CommonFields []catalogFieldNote `json:"commonFields"`
	Tables       []catalogTable     `json:"tables"`
}

type catalogExclusion struct {
	Name   string `json:"name"`
	Reason string `json:"reason"`
}

type catalogDomain struct {
	Key         string   `json:"key"`
	Title       string   `json:"title"`
	File        string   `json:"file"`
	Order       int      `json:"order"`
	Description string   `json:"description"`
	References  []string `json:"references"`
}

type catalogFieldNote struct {
	Name string `json:"name"`
	Note string `json:"note"`
}

type catalogTable struct {
	Name            string             `json:"name"`
	Title           string             `json:"title"`
	Domain          string             `json:"domain"`
	Kind            string             `json:"kind"`
	Purpose         string             `json:"purpose"`
	Boundary        string             `json:"boundary"`
	Lifecycle       string             `json:"lifecycle"`
	WriteBoundary   string             `json:"writeBoundary"`
	Notes           string             `json:"notes"`
	SensitiveFields []string           `json:"sensitiveFields"`
	FieldNotes      []catalogFieldNote `json:"fieldNotes"`
	SchemaSources   []string           `json:"schemaSources"`
	References      []string           `json:"references"`
}

type catalogIndex struct {
	domains      map[string]catalogDomain
	tables       map[string]catalogTable
	commonFields map[string]string
}

type databaseSchema struct {
	Tables []databaseTable
}

type databaseTable struct {
	Name        string
	Schema      string
	Comment     string
	View        bool
	Columns     []databaseColumn
	PrimaryKey  []string
	ForeignKeys []databaseForeignKey
	Indexes     []databaseIndex
	Checks      []databaseCheck
}

type databaseColumn struct {
	Name         string
	LogicalType  string
	PostgresType string
	Nullable     bool
	Unique       bool
	Increment    bool
	HasDefault   bool
	Default      string
	Enums        []string
	Attr         string
	Key          string
	Collation    string
	Comment      string
}

type databaseForeignKey struct {
	Symbol     string
	Columns    []string
	RefTable   string
	RefSchema  string
	RefColumns []string
	OnUpdate   string
	OnDelete   string
}

type databaseIndex struct {
	Name      string
	Unique    bool
	Columns   []string
	Predicate string
}

type databaseCheck struct {
	Name       string
	Expression string
}

type schemaMetrics struct {
	Tables         int
	Columns        int
	ForeignKeys    int
	Indexes        int
	PartialIndexes int
	Checks         int
}

type outputReport struct {
	Missing    []string
	Changed    []string
	Stale      []string
	Unexpected []string
}

func main() {
	if err := run(os.Args[1:], os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "schema-doc:", err)
		os.Exit(1)
	}
}

func run(args []string, stdout io.Writer) error {
	flags := flag.NewFlagSet("schema-doc", flag.ContinueOnError)
	flags.SetOutput(stdout)
	var (
		checkMode  bool
		writeMode  bool
		catalogArg string
		outputArg  string
	)
	flags.BoolVar(&checkMode, "check", false, "check generated database documentation without writing")
	flags.BoolVar(&writeMode, "write", false, "write generated database documentation")
	flags.StringVar(&catalogArg, "catalog", "", "catalog path, relative to repository root unless absolute")
	flags.StringVar(&outputArg, "out", "", "output directory, relative to repository root unless absolute")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return fmt.Errorf("unexpected positional arguments: %s", strings.Join(flags.Args(), " "))
	}
	if checkMode == writeMode {
		return errors.New("exactly one of --check or --write is required")
	}

	cwd, err := os.Getwd()
	if err != nil {
		return fmt.Errorf("get working directory: %w", err)
	}
	repoRoot, err := findRepoRoot(cwd)
	if err != nil {
		return err
	}
	catalogPath := resolveRootPath(repoRoot, catalogArg, "server/docs/database/table-catalog.json")
	outputDir := resolveRootPath(repoRoot, outputArg, "server/docs/database")

	catalogValue, err := loadCatalog(catalogPath)
	if err != nil {
		return err
	}
	db, err := extractDatabaseSchema(entmigrate.Tables)
	if err != nil {
		return err
	}
	outputs, err := buildOutputs(db, catalogValue, repoRoot, outputDir)
	if err != nil {
		return err
	}

	mode := "check"
	if writeMode {
		mode = "write"
		report, err := inspectOutputs(outputDir, outputs)
		if err != nil {
			return err
		}
		if len(report.Stale) > 0 || len(report.Unexpected) > 0 {
			return fmt.Errorf(
				"refusing to write while output directory contains obsolete or manual Markdown: %s",
				formatOutputReport(report),
			)
		}
		if err := writeOutputs(outputDir, outputs); err != nil {
			return err
		}
	}

	report, err := inspectOutputs(outputDir, outputs)
	if err != nil {
		return err
	}
	if !report.clean() {
		return fmt.Errorf("generated database documentation is not current: %s", formatOutputReport(report))
	}
	metrics := db.metrics()
	if _, err := fmt.Fprintf(
		stdout,
		"schema-doc: mode=%s tables=%d catalog=%d columns=%d foreignKeys=%d indexes=%d checks=%d outputs=%d missing=0 changed=0 stale=0 unexpected=0\n",
		mode,
		metrics.Tables,
		len(catalogValue.Tables),
		metrics.Columns,
		metrics.ForeignKeys,
		metrics.Indexes,
		metrics.Checks,
		len(outputs),
	); err != nil {
		return fmt.Errorf("write schema-doc summary: %w", err)
	}
	return nil
}

func resolveRootPath(repoRoot, value, fallback string) string {
	if value == "" {
		value = fallback
	}
	if filepath.IsAbs(value) {
		return filepath.Clean(value)
	}
	return filepath.Join(repoRoot, filepath.FromSlash(value))
}

func findRepoRoot(start string) (string, error) {
	current, err := filepath.Abs(start)
	if err != nil {
		return "", fmt.Errorf("resolve working directory: %w", err)
	}
	for {
		if regularFile(filepath.Join(current, "server", "go.mod")) &&
			regularFile(filepath.Join(current, "docs", "文档清单.md")) {
			return current, nil
		}
		parent := filepath.Dir(current)
		if parent == current {
			return "", fmt.Errorf("repository root not found from %s", start)
		}
		current = parent
	}
}

func regularFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}

func loadCatalog(path string) (result catalog, resultErr error) {
	file, err := os.Open(path)
	if err != nil {
		return catalog{}, fmt.Errorf("open catalog %s: %w", path, err)
	}
	defer func() {
		if closeErr := file.Close(); closeErr != nil && resultErr == nil {
			resultErr = fmt.Errorf("close catalog %s: %w", path, closeErr)
		}
	}()

	decoder := json.NewDecoder(file)
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&result); err != nil {
		return catalog{}, fmt.Errorf("decode catalog %s: %w", path, err)
	}
	var trailing any
	if err := decoder.Decode(&trailing); !errors.Is(err, io.EOF) {
		if err == nil {
			return catalog{}, fmt.Errorf("decode catalog %s: trailing JSON value", path)
		}
		return catalog{}, fmt.Errorf("decode catalog %s trailing content: %w", path, err)
	}
	return result, nil
}

func extractDatabaseSchema(tables []*sqlschema.Table) (databaseSchema, error) {
	db := databaseSchema{Tables: make([]databaseTable, 0, len(tables))}
	seen := make(map[string]struct{}, len(tables))
	for _, source := range tables {
		if source == nil || strings.TrimSpace(source.Name) == "" {
			return databaseSchema{}, errors.New("generated schema contains a nil or unnamed table")
		}
		if _, ok := seen[source.Name]; ok {
			return databaseSchema{}, fmt.Errorf("generated schema contains duplicate table %q", source.Name)
		}
		seen[source.Name] = struct{}{}
		table := databaseTable{
			Name:    source.Name,
			Schema:  source.Schema,
			Comment: source.Comment,
			View:    source.View,
		}
		if table.Schema == "" {
			table.Schema = "public"
		}

		columnNames := make(map[string]struct{}, len(source.Columns))
		for _, sourceColumn := range source.Columns {
			if sourceColumn == nil || strings.TrimSpace(sourceColumn.Name) == "" {
				return databaseSchema{}, fmt.Errorf("table %s contains a nil or unnamed column", source.Name)
			}
			if _, ok := columnNames[sourceColumn.Name]; ok {
				return databaseSchema{}, fmt.Errorf("table %s contains duplicate column %s", source.Name, sourceColumn.Name)
			}
			columnNames[sourceColumn.Name] = struct{}{}
			postgresType, err := postgresColumnType(sourceColumn)
			if err != nil {
				return databaseSchema{}, fmt.Errorf("table %s column %s: %w", source.Name, sourceColumn.Name, err)
			}
			defaultValue, hasDefault, err := postgresColumnDefault(sourceColumn)
			if err != nil {
				return databaseSchema{}, fmt.Errorf("table %s column %s: %w", source.Name, sourceColumn.Name, err)
			}
			table.Columns = append(table.Columns, databaseColumn{
				Name:         sourceColumn.Name,
				LogicalType:  sourceColumn.Type.String(),
				PostgresType: postgresType,
				Nullable:     sourceColumn.Nullable,
				Unique:       sourceColumn.Unique,
				Increment:    sourceColumn.Increment,
				HasDefault:   hasDefault,
				Default:      defaultValue,
				Enums:        append([]string(nil), sourceColumn.Enums...),
				Attr:         sourceColumn.Attr,
				Key:          sourceColumn.Key,
				Collation:    sourceColumn.Collation,
				Comment:      sourceColumn.Comment,
			})
		}

		for _, primaryColumn := range source.PrimaryKey {
			if primaryColumn == nil {
				return databaseSchema{}, fmt.Errorf("table %s contains a nil primary-key column", source.Name)
			}
			table.PrimaryKey = append(table.PrimaryKey, primaryColumn.Name)
		}

		for _, sourceForeignKey := range source.ForeignKeys {
			if sourceForeignKey == nil || sourceForeignKey.RefTable == nil {
				return databaseSchema{}, fmt.Errorf("table %s contains an incomplete foreign key", source.Name)
			}
			foreignKey := databaseForeignKey{
				Symbol:    sourceForeignKey.Symbol,
				RefTable:  sourceForeignKey.RefTable.Name,
				RefSchema: sourceForeignKey.RefTable.Schema,
				OnUpdate:  string(sourceForeignKey.OnUpdate),
				OnDelete:  string(sourceForeignKey.OnDelete),
			}
			if foreignKey.RefSchema == "" {
				foreignKey.RefSchema = "public"
			}
			for _, column := range sourceForeignKey.Columns {
				if column == nil {
					return databaseSchema{}, fmt.Errorf("table %s contains a foreign key with a nil local column", source.Name)
				}
				foreignKey.Columns = append(foreignKey.Columns, column.Name)
			}
			for _, column := range sourceForeignKey.RefColumns {
				if column == nil {
					return databaseSchema{}, fmt.Errorf("table %s contains a foreign key with a nil referenced column", source.Name)
				}
				foreignKey.RefColumns = append(foreignKey.RefColumns, column.Name)
			}
			if len(foreignKey.Columns) == 0 || len(foreignKey.Columns) != len(foreignKey.RefColumns) {
				return databaseSchema{}, fmt.Errorf("table %s contains a malformed foreign key %s", source.Name, sourceForeignKey.Symbol)
			}
			table.ForeignKeys = append(table.ForeignKeys, foreignKey)
		}
		sort.Slice(table.ForeignKeys, func(left, right int) bool {
			leftKey := table.ForeignKeys[left].Symbol + "\x00" + strings.Join(table.ForeignKeys[left].Columns, ",")
			rightKey := table.ForeignKeys[right].Symbol + "\x00" + strings.Join(table.ForeignKeys[right].Columns, ",")
			return leftKey < rightKey
		})

		for _, sourceIndex := range source.Indexes {
			if sourceIndex == nil {
				return databaseSchema{}, fmt.Errorf("table %s contains a nil index", source.Name)
			}
			indexValue := databaseIndex{Name: sourceIndex.Name, Unique: sourceIndex.Unique}
			for _, column := range sourceIndex.Columns {
				if column == nil {
					return databaseSchema{}, fmt.Errorf("table %s index %s contains a nil column", source.Name, sourceIndex.Name)
				}
				indexValue.Columns = append(indexValue.Columns, column.Name)
			}
			if annotation := sourceIndex.Annotation; annotation != nil {
				if annotation.Prefix != 0 ||
					len(annotation.PrefixColumns) != 0 ||
					annotation.Desc ||
					len(annotation.DescColumns) != 0 ||
					len(annotation.IncludeColumns) != 0 ||
					annotation.Type != "" ||
					len(annotation.Types) != 0 ||
					annotation.OpClass != "" ||
					len(annotation.OpClassColumns) != 0 {
					return databaseSchema{}, fmt.Errorf(
						"table %s index %s uses an index annotation not supported by schema-doc v1",
						source.Name,
						sourceIndex.Name,
					)
				}
				indexValue.Predicate = strings.TrimSpace(annotation.Where)
			}
			table.Indexes = append(table.Indexes, indexValue)
		}
		sort.Slice(table.Indexes, func(left, right int) bool {
			leftKey := table.Indexes[left].Name + "\x00" + strings.Join(table.Indexes[left].Columns, ",")
			rightKey := table.Indexes[right].Name + "\x00" + strings.Join(table.Indexes[right].Columns, ",")
			return leftKey < rightKey
		})

		if source.Annotation != nil {
			if expression := strings.TrimSpace(source.Annotation.Check); expression != "" {
				table.Checks = append(table.Checks, databaseCheck{Name: "未命名 CHECK", Expression: expression})
			}
			names := make([]string, 0, len(source.Annotation.Checks))
			for name := range source.Annotation.Checks {
				names = append(names, name)
			}
			sort.Strings(names)
			for _, name := range names {
				table.Checks = append(table.Checks, databaseCheck{
					Name:       name,
					Expression: strings.TrimSpace(source.Annotation.Checks[name]),
				})
			}
		}
		db.Tables = append(db.Tables, table)
	}
	sort.Slice(db.Tables, func(left, right int) bool {
		leftKey := db.Tables[left].Schema + "\x00" + db.Tables[left].Name
		rightKey := db.Tables[right].Schema + "\x00" + db.Tables[right].Name
		return leftKey < rightKey
	})
	return db, nil
}

func postgresColumnType(column *sqlschema.Column) (string, error) {
	if schemaType := strings.TrimSpace(column.SchemaType[dialect.Postgres]); schemaType != "" {
		return schemaType, nil
	}
	switch column.Type {
	case field.TypeBool:
		return "boolean", nil
	case field.TypeInt8, field.TypeUint8, field.TypeInt16:
		return "smallint", nil
	case field.TypeUint16, field.TypeInt32:
		return "integer", nil
	case field.TypeUint32, field.TypeInt, field.TypeUint, field.TypeInt64, field.TypeUint64:
		return "bigint", nil
	case field.TypeFloat32:
		return "real", nil
	case field.TypeFloat64:
		return "double precision", nil
	case field.TypeBytes:
		return "bytea", nil
	case field.TypeUUID:
		return "uuid", nil
	case field.TypeJSON:
		return "jsonb", nil
	case field.TypeTime:
		return "timestamp with time zone", nil
	case field.TypeString, field.TypeEnum:
		if column.Size > postgresMaxVarchar {
			return "text", nil
		}
		if column.Size > 0 {
			return fmt.Sprintf("varchar(%d)", column.Size), nil
		}
		return "varchar", nil
	case field.TypeOther:
		return "", errors.New("other type requires SchemaType[postgres]")
	default:
		return "", fmt.Errorf("unsupported Ent field type %s", column.Type.String())
	}
}

func postgresColumnDefault(column *sqlschema.Column) (string, bool, error) {
	if column.Default == nil {
		return "", false, nil
	}
	switch value := column.Default.(type) {
	case sqlschema.Expr:
		return string(value), true, nil
	case map[string]sqlschema.Expr:
		expression, ok := value[dialect.Postgres]
		if !ok || strings.TrimSpace(string(expression)) == "" {
			return "", false, errors.New("dialect default expression does not define postgres")
		}
		return string(expression), true, nil
	case string:
		postgresType := strings.ToLower(strings.TrimSpace(column.SchemaType[dialect.Postgres]))
		if column.Type.Numeric() ||
			strings.HasPrefix(postgresType, "numeric") ||
			strings.HasPrefix(postgresType, "decimal") {
			return value, true, nil
		}
		return "'" + strings.ReplaceAll(value, "'", "''") + "'", true, nil
	case bool:
		return strconv.FormatBool(value), true, nil
	case int:
		return strconv.FormatInt(int64(value), 10), true, nil
	case int8:
		return strconv.FormatInt(int64(value), 10), true, nil
	case int16:
		return strconv.FormatInt(int64(value), 10), true, nil
	case int32:
		return strconv.FormatInt(int64(value), 10), true, nil
	case int64:
		return strconv.FormatInt(value, 10), true, nil
	case uint:
		return strconv.FormatUint(uint64(value), 10), true, nil
	case uint8:
		return strconv.FormatUint(uint64(value), 10), true, nil
	case uint16:
		return strconv.FormatUint(uint64(value), 10), true, nil
	case uint32:
		return strconv.FormatUint(uint64(value), 10), true, nil
	case uint64:
		return strconv.FormatUint(value, 10), true, nil
	case float32:
		return strconv.FormatFloat(float64(value), 'g', -1, 32), true, nil
	case float64:
		return strconv.FormatFloat(value, 'g', -1, 64), true, nil
	default:
		return "", false, fmt.Errorf("unsupported database default value type %T", column.Default)
	}
}

func (db databaseSchema) metrics() schemaMetrics {
	metrics := schemaMetrics{Tables: len(db.Tables)}
	for _, table := range db.Tables {
		metrics.Columns += len(table.Columns)
		metrics.ForeignKeys += len(table.ForeignKeys)
		metrics.Indexes += len(table.Indexes)
		metrics.Checks += len(table.Checks)
		for _, indexValue := range table.Indexes {
			if indexValue.Predicate != "" {
				metrics.PartialIndexes++
			}
		}
	}
	return metrics
}

func buildOutputs(db databaseSchema, catalogValue catalog, repoRoot, outputDir string) (map[string][]byte, error) {
	index, err := validateCatalog(db, catalogValue, repoRoot)
	if err != nil {
		return nil, err
	}
	outputs := make(map[string][]byte, len(catalogValue.Domains)+1)
	readme, err := renderReadme(db, catalogValue, index)
	if err != nil {
		return nil, err
	}
	outputs["README.md"] = readme

	domains := append([]catalogDomain(nil), catalogValue.Domains...)
	sort.Slice(domains, func(left, right int) bool {
		if domains[left].Order == domains[right].Order {
			return domains[left].Key < domains[right].Key
		}
		return domains[left].Order < domains[right].Order
	})
	for _, domainValue := range domains {
		document, err := renderDomain(db, domainValue, index, repoRoot, outputDir)
		if err != nil {
			return nil, err
		}
		outputs[domainValue.File] = document
	}
	return outputs, nil
}

func validateCatalog(db databaseSchema, value catalog, repoRoot string) (catalogIndex, error) {
	if value.Version != 1 {
		return catalogIndex{}, fmt.Errorf("catalog version must be 1, got %d", value.Version)
	}
	if strings.TrimSpace(value.Description) == "" {
		return catalogIndex{}, errors.New("catalog description is required")
	}

	index := catalogIndex{
		domains:      make(map[string]catalogDomain, len(value.Domains)),
		tables:       make(map[string]catalogTable, len(value.Tables)),
		commonFields: make(map[string]string, len(value.CommonFields)),
	}
	domainFiles := make(map[string]struct{}, len(value.Domains))
	domainOrders := make(map[int]struct{}, len(value.Domains))
	for _, domainValue := range value.Domains {
		if strings.TrimSpace(domainValue.Key) == "" ||
			strings.TrimSpace(domainValue.Title) == "" ||
			strings.TrimSpace(domainValue.Description) == "" {
			return catalogIndex{}, errors.New("every catalog domain requires key, title, and description")
		}
		if _, ok := index.domains[domainValue.Key]; ok {
			return catalogIndex{}, fmt.Errorf("duplicate catalog domain %q", domainValue.Key)
		}
		if domainValue.Order <= 0 {
			return catalogIndex{}, fmt.Errorf("catalog domain %s order must be positive", domainValue.Key)
		}
		if _, ok := domainOrders[domainValue.Order]; ok {
			return catalogIndex{}, fmt.Errorf("duplicate catalog domain order %d", domainValue.Order)
		}
		domainOrders[domainValue.Order] = struct{}{}
		if filepath.Base(domainValue.File) != domainValue.File ||
			filepath.Ext(domainValue.File) != ".md" ||
			domainValue.File == "README.md" {
			return catalogIndex{}, fmt.Errorf("catalog domain %s has invalid generated filename %q", domainValue.Key, domainValue.File)
		}
		if _, ok := domainFiles[domainValue.File]; ok {
			return catalogIndex{}, fmt.Errorf("duplicate catalog domain output %q", domainValue.File)
		}
		domainFiles[domainValue.File] = struct{}{}
		if err := validateReferences(repoRoot, domainValue.References); err != nil {
			return catalogIndex{}, fmt.Errorf("catalog domain %s: %w", domainValue.Key, err)
		}
		index.domains[domainValue.Key] = domainValue
	}
	if len(index.domains) == 0 {
		return catalogIndex{}, errors.New("catalog requires at least one domain")
	}

	allColumnNames := make(map[string]struct{})
	dbTables := make(map[string]databaseTable, len(db.Tables))
	for _, table := range db.Tables {
		dbTables[table.Name] = table
		for _, column := range table.Columns {
			allColumnNames[column.Name] = struct{}{}
		}
	}
	for _, common := range value.CommonFields {
		if strings.TrimSpace(common.Name) == "" || strings.TrimSpace(common.Note) == "" {
			return catalogIndex{}, errors.New("every common field requires name and note")
		}
		if _, ok := index.commonFields[common.Name]; ok {
			return catalogIndex{}, fmt.Errorf("duplicate common field note %q", common.Name)
		}
		if _, ok := allColumnNames[common.Name]; !ok {
			return catalogIndex{}, fmt.Errorf("common field note %q does not match any generated column", common.Name)
		}
		index.commonFields[common.Name] = common.Note
	}

	for _, tableValue := range value.Tables {
		if strings.TrimSpace(tableValue.Name) == "" ||
			strings.TrimSpace(tableValue.Title) == "" ||
			strings.TrimSpace(tableValue.Purpose) == "" ||
			strings.TrimSpace(tableValue.Boundary) == "" ||
			strings.TrimSpace(tableValue.Lifecycle) == "" ||
			strings.TrimSpace(tableValue.WriteBoundary) == "" {
			return catalogIndex{}, fmt.Errorf("catalog table %q is missing required narrative fields", tableValue.Name)
		}
		if _, ok := index.tables[tableValue.Name]; ok {
			return catalogIndex{}, fmt.Errorf("duplicate catalog table %q", tableValue.Name)
		}
		if _, ok := classificationLabels[tableValue.Kind]; !ok {
			return catalogIndex{}, fmt.Errorf("catalog table %s has unsupported kind %q", tableValue.Name, tableValue.Kind)
		}
		if _, ok := index.domains[tableValue.Domain]; !ok {
			return catalogIndex{}, fmt.Errorf("catalog table %s references unknown domain %q", tableValue.Name, tableValue.Domain)
		}
		generatedTable, ok := dbTables[tableValue.Name]
		if !ok {
			return catalogIndex{}, fmt.Errorf("catalog contains extra table %q", tableValue.Name)
		}
		fields := make(map[string]struct{}, len(generatedTable.Columns))
		for _, column := range generatedTable.Columns {
			fields[column.Name] = struct{}{}
		}
		if err := validateNamedFieldList(tableValue.Name, "sensitiveFields", tableValue.SensitiveFields, fields); err != nil {
			return catalogIndex{}, err
		}
		fieldNotes := make(map[string]struct{}, len(tableValue.FieldNotes))
		for _, note := range tableValue.FieldNotes {
			if strings.TrimSpace(note.Name) == "" || strings.TrimSpace(note.Note) == "" {
				return catalogIndex{}, fmt.Errorf("catalog table %s has an incomplete field note", tableValue.Name)
			}
			if _, ok := fields[note.Name]; !ok {
				return catalogIndex{}, fmt.Errorf("catalog table %s field note references unknown column %q", tableValue.Name, note.Name)
			}
			if _, ok := fieldNotes[note.Name]; ok {
				return catalogIndex{}, fmt.Errorf("catalog table %s has duplicate field note %q", tableValue.Name, note.Name)
			}
			fieldNotes[note.Name] = struct{}{}
		}
		sources := tableSchemaSources(tableValue)
		if err := validateRepositoryFiles(repoRoot, sources, ".go"); err != nil {
			return catalogIndex{}, fmt.Errorf("catalog table %s schema source: %w", tableValue.Name, err)
		}
		if err := validateReferences(repoRoot, tableValue.References); err != nil {
			return catalogIndex{}, fmt.Errorf("catalog table %s: %w", tableValue.Name, err)
		}
		index.tables[tableValue.Name] = tableValue
	}

	missing := make([]string, 0)
	for _, table := range db.Tables {
		if _, ok := index.tables[table.Name]; !ok {
			missing = append(missing, table.Name)
		}
	}
	if len(missing) > 0 {
		return catalogIndex{}, fmt.Errorf("catalog is missing generated tables: %s", strings.Join(missing, ", "))
	}

	exclusions := make(map[string]struct{}, len(value.Exclusions))
	for _, exclusion := range value.Exclusions {
		if strings.TrimSpace(exclusion.Name) == "" || strings.TrimSpace(exclusion.Reason) == "" {
			return catalogIndex{}, errors.New("every catalog exclusion requires name and reason")
		}
		if _, ok := exclusions[exclusion.Name]; ok {
			return catalogIndex{}, fmt.Errorf("duplicate catalog exclusion %q", exclusion.Name)
		}
		if _, ok := dbTables[exclusion.Name]; ok {
			return catalogIndex{}, fmt.Errorf("catalog exclusion %q is also a generated application table", exclusion.Name)
		}
		exclusions[exclusion.Name] = struct{}{}
	}
	return index, nil
}

func validateNamedFieldList(tableName, label string, values []string, fields map[string]struct{}) error {
	seen := make(map[string]struct{}, len(values))
	for _, value := range values {
		if strings.TrimSpace(value) == "" {
			return fmt.Errorf("catalog table %s %s contains an empty field", tableName, label)
		}
		if _, ok := fields[value]; !ok {
			return fmt.Errorf("catalog table %s %s references unknown column %q", tableName, label, value)
		}
		if _, ok := seen[value]; ok {
			return fmt.Errorf("catalog table %s %s contains duplicate column %q", tableName, label, value)
		}
		seen[value] = struct{}{}
	}
	return nil
}

func validateReferences(repoRoot string, references []string) error {
	return validateRepositoryFiles(repoRoot, references, ".md")
}

func validateRepositoryFiles(repoRoot string, paths []string, extension string) error {
	seen := make(map[string]struct{}, len(paths))
	for _, value := range paths {
		if strings.TrimSpace(value) == "" {
			return errors.New("repository path cannot be empty")
		}
		if filepath.IsAbs(value) {
			return fmt.Errorf("repository path must be relative: %s", value)
		}
		clean := filepath.Clean(filepath.FromSlash(value))
		if clean == "." || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
			return fmt.Errorf("repository path escapes root: %s", value)
		}
		if filepath.Ext(clean) != extension {
			return fmt.Errorf("repository path must end in %s: %s", extension, value)
		}
		if _, ok := seen[clean]; ok {
			return fmt.Errorf("duplicate repository path: %s", value)
		}
		seen[clean] = struct{}{}
		absolute := filepath.Join(repoRoot, clean)
		relative, err := filepath.Rel(repoRoot, absolute)
		if err != nil || relative == ".." || strings.HasPrefix(relative, ".."+string(filepath.Separator)) {
			return fmt.Errorf("repository path escapes root: %s", value)
		}
		if !regularFile(absolute) {
			return fmt.Errorf("repository file does not exist: %s", value)
		}
	}
	return nil
}

func tableSchemaSources(tableValue catalogTable) []string {
	if len(tableValue.SchemaSources) > 0 {
		return append([]string(nil), tableValue.SchemaSources...)
	}
	base := tableValue.Name
	switch base {
	case "processes":
		base = "process"
	default:
		if strings.HasSuffix(base, "ies") {
			base = strings.TrimSuffix(base, "ies") + "y"
		} else if strings.HasSuffix(base, "ches") ||
			strings.HasSuffix(base, "shes") ||
			strings.HasSuffix(base, "xes") ||
			strings.HasSuffix(base, "zes") {
			base = strings.TrimSuffix(base, "es")
		} else {
			base = strings.TrimSuffix(base, "s")
		}
	}
	return []string{"server/internal/data/model/schema/" + base + ".go"}
}

