import { expect } from 'playwright/test'

export function createDevVisualizationScenarios({ assert, assertNoHorizontalOverflow }) {
  return [{
    name: 'dev-visualization-standards-desktop',
    path: '/__dev/visualization',
    viewport: { width: 1166, height: 984 },
    verify: async (page) => {
      const businessRequests = []
      page.on('request', (request) => {
        const { pathname } = new URL(request.url())
        if (/^\/(?:api|rpc|templates)(?:\/|$)/u.test(pathname)) businessRequests.push(pathname)
      })
      const directory = page.getByRole('navigation', { name: '图例类别', exact: true })
      const choose = (name) => directory.getByRole('button', { name, exact: true }).click()
      const active = page.getByRole('region', { name: '当前类别图例', exact: true })
      await expect(directory.getByRole('button')).toHaveCount(9)
      await expect(page.getByText('9 类 · 11 个图例', { exact: true })).toBeVisible()
      await expect(directory.getByRole('button', { name: '流程规则', exact: true })).toHaveAttribute('aria-pressed', 'true')
      await expect(active.getByRole('heading', { name: '采购收货：规则允许怎么走？' })).toBeVisible()
      await choose('计划安排')
      await expect(active.getByText(/有计划起止时间可画排程图/u)).toBeVisible()
      const dueDay = active.getByRole('button', { name: '11 月 16 日，1 项待办', exact: true })
      await dueDay.press('Enter')
      await expect(dueDay).toHaveAttribute('aria-pressed', 'true')
      await expect(active.getByText('核对订单交期', { exact: true })).toBeVisible()
      await active.getByRole('button', { name: '未设日期 1', exact: true }).click()
      await expect(active.getByText('补齐用料资料', { exact: true })).toBeVisible()

      await choose('办理进度')
      await active.getByRole('button', { name: '服务端检查', exact: true }).click()
      await expect(active.getByRole('status')).toContainText('等待 1 分钟，执行 2 分钟')
      await expect(active.getByText(/总耗时 8 分钟/u)).toBeVisible()

      await choose('表格对照')
      await active.getByRole('button', { name: '只看改动', exact: true }).click()
      await expect(active.getByRole('row', { name: /采购管理/u })).toHaveCount(0)
      await active.getByRole('button', { name: '打印版式，打印核对，失败', exact: true }).click()
      await expect(active.getByText(/样例签字区被截断/u)).toBeVisible()
      await choose('计划安排')
      await expect(active.getByText('补齐用料资料', { exact: true })).toBeVisible()
      await choose('表格对照')
      await expect(active.getByRole('button', { name: '打印版式，打印核对，失败', exact: true })).toHaveAttribute('aria-pressed', 'true')

      await choose('流程规则')
      const graph = active.getByRole('region', { name: '采购收货：规则允许怎么走？' }).locator('[data-mermaid-status="rendered"]')
      await expect(graph).toBeVisible()
      const icons = await graph.locator('svg.label-icon').evaluateAll((items) => items.map((icon) => ({
        width: parseFloat(getComputedStyle(icon).width), height: parseFloat(getComputedStyle(icon).height),
      })))
      assert.equal(icons.length, 5, '按真实节点类型提供本地图标')
      assert(icons.every(({ width, height }) => width > 0 && width <= 20 && height > 0 && height <= 20), '画布缩放规则不得撑大节点图标')
      const branch = graph.getByRole('button', { name: '本行暂不入库', exact: true })
      const shape = branch.locator('.label-container').first()
      const before = await shape.evaluate((node) => ({ stroke: getComputedStyle(node).stroke, dash: getComputedStyle(node).strokeDasharray }))
      await branch.press('Enter')
      const after = await shape.evaluate((node) => ({ stroke: getComputedStyle(node).stroke, dash: getComputedStyle(node).strokeDasharray, outline: getComputedStyle(node).outlineStyle }))
      assert.equal(after.stroke, before.stroke, '选中保留异常色')
      assert.equal(after.dash, before.dash, '选中保留分支虚线')
      assert.notEqual(after.dash, 'none')
      assert.equal(after.outline, 'solid')
      await graph.getByRole('button', { name: '采购办理处置', exact: true }).press('Enter')
      await expect(active.getByRole('status')).toContainText('保留原拒收结论')

      await active.getByText('看这笔进度', { exact: true }).click()
      await expect(active.getByRole('radio', { name: '看这笔进度' })).toBeChecked()
      await expect(page).toHaveURL(/type=progress/u)
      await expect(directory.getByRole('button', { name: '办理进度' })).toHaveAttribute('aria-pressed', 'true')
      await expect(active.getByText('当前 · 仓库确认入库')).toBeVisible()
      await active.getByText('看收货规则', { exact: true }).click()
      await expect(active.getByRole('radio', { name: '看收货规则' })).toBeChecked()
      await expect(page).toHaveURL(/type=flow/u)
      await expect(active.getByRole('status')).toContainText('保留原拒收结论')
      await page.goBack()
      await expect(active.getByRole('heading', { name: '这笔收货走到哪？' })).toBeVisible()

      await choose('结构关系')
      await expect(active.getByRole('region', { name: '工作台：模块归哪一类？' }).locator('[data-mermaid-status="rendered"]')).toBeVisible()
      await expect(active.getByRole('heading', { name: '工作台：模块归哪一类？', exact: true })).toBeVisible()
      await choose('操作步骤')
      await expect(active.getByText('右侧切到所选模板。', { exact: true })).toBeVisible()

      await choose('统计图表')
      await active.getByRole('button', { name: '延迟 2 单', exact: true }).focus()
      await expect(active.getByRole('status')).toContainText('延迟 2 / 10 单，占 20%')
      await page.keyboard.press('Escape')
      await expect(active.getByRole('status')).toContainText('按期 8 / 10 单，占 80%')
      await active.getByText('表格', { exact: true }).click()
      await expect(active.getByRole('row', { name: '延迟 2 单 20%', exact: true })).toBeVisible()

      await choose('区域标注')
      const marker = active.locator('.erp-document-guide__marker').nth(1)
      await expect(marker).toBeVisible()
      await marker.press('Enter')
      await expect(marker).toHaveAttribute('aria-pressed', 'true')
      await active.getByRole('button', { name: '看打印效果', exact: true }).click()
      await expect(marker).toBeHidden()
      await active.getByRole('button', { name: '返回标注说明', exact: true }).click()
      await expect(marker).toHaveAttribute('aria-pressed', 'true')

      await choose('交互演示')
      const trigger = active.getByRole('button', { name: '选择演示材料', exact: true })
      await trigger.click()
      const dialog = page.getByRole('dialog', { name: '从演示材料库添加', exact: true })
      await expect(dialog).toBeVisible()
      const confirm = dialog.getByRole('button', { name: '添加到演示结果', exact: true })
      await expect(confirm).toBeDisabled()
      await dialog.getByRole('row', { name: /短毛绒/u }).getByRole('checkbox').check()
      await confirm.click()
      await expect(dialog).toBeHidden()
      await expect(active.getByLabel('来源选择示例结果', { exact: true })).toHaveText('已添加 1 条：短毛绒')
      await expect(trigger).toBeFocused()
      assert.deepEqual(businessRequests, [], '图例不读写业务接口')

      await choose('计划安排')
      for (const width of [1166, 805]) {
        await page.setViewportSize({ width, height: 984 })
        await assertNoHorizontalOverflow(page, `可视化规范 ${width}`)
      }
      const source = page.getByRole('link', { name: '规则源文档', exact: true })
      await source.click()
      await expect(page).toHaveURL(/#visualization-choices$/u)
      await expect(page.getByRole('heading', { name: /选择表达/u })).toBeVisible()
      const guide = page.locator('.erp-dev-docs-markdown')
      await guide.getByRole('heading', { name: /页内理解与上下文/u }).scrollIntoViewIfNeeded()
      await expect(guide.locator('svg').getByText('恢复筛选、选中项和位置', { exact: true }).first()).toBeVisible()
      await page.goBack()
      await page.reload()
      await expect(directory.getByRole('button', { name: '计划安排', exact: true })).toHaveAttribute('aria-pressed', 'true')
      await choose('流程规则')
      await expect(graph).toBeVisible()
      await assertNoHorizontalOverflow(page, '采购收货图例对照 805')
      await page.setViewportSize({ width: 1166, height: 984 })
      await expect(active.getByText('分支流程图', { exact: true })).toBeVisible()
    },
  }]
}
