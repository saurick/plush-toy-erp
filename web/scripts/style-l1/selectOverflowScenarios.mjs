import { assertSingleSelectValues } from './singleSelectAssertions.mjs'
import { assertBusinessNoteTextAreas } from './businessFormPageAssertions.mjs'
import { waitForFiniteAnimations } from './browserReadiness.mjs'

export function createSelectOverflowScenarios({ assert, assertNoHorizontalOverflow }) {
  return [{
    name: 'dev-ui-select-overflow',
    path: '/__dev/ui-design?page=controls&control=select-overflow',
    viewport: { width: 1920, height: 1080 },
    deviceScaleFactor: 2,
    verify: async (page) => {
      const sample = page.getByRole('region', { name: '长值与多列样例', exact: true })
      await sample.waitFor()
      const control = (name) => sample.getByRole('combobox', { name, exact: true }).locator('xpath=ancestor::*[contains(concat(" ", normalize-space(@class), " "), " app-select ")][1]')
      const product = control('第 1 行产品')
      const warehouse = control('第 1 行仓库')
      const productField = product.locator('xpath=..')
      const name = product.locator('.app-select__reference-name')
      const nameBox = await name.boundingBox()
      const controlBox = await product.boundingBox()
      const normalHeight = await product.evaluate((node) => parseFloat(getComputedStyle(node).getPropertyValue('--erp-form-control-height')) || 36)
      assert(controlBox.height > normalHeight && nameBox.height > 24, '长名称自然换行并撑高输入框')
      assert((await name.innerText()).includes('独立包装规格 27016-1'), '锁定名称的尾部直接可读')
      assert.equal(await productField.locator('.app-select__reference-code').count(), 0, '选中名称下不重复显示编码')
      assert(await product.getByRole('combobox').isDisabled(), '名称展开不解除来源锁定')
      assert.equal(await sample.getByRole('button', { name: /查看.*完整值/u }).count(), 0, '选择框不增加完整值图标')
      await assertSingleSelectValues(sample, '长引用初始显示', 6)
      assert(!(await control('第 1 行 SKU').innerText()).includes('EXPORT-PACK'), '规格编码留在候选项，不混入已选名称')

      await warehouse.getByRole('combobox').fill('FINISHED')
      const menu = page.locator('.ant-select-dropdown:visible')
      await menu.locator('.ant-select-item-option').first().waitFor()
      await waitForFiniteAnimations(page)
      assert((await menu.boundingBox()).width >= 559, '业务引用候选列表独立加宽到 560px')
      const option = menu.getByText('成品仓 · 东莞二厂 B 区出口订单待出货产品与独立包装存放区 WH-FINISHED-02', { exact: true })
      const optionSize = await option.evaluate((node) => ({ client: node.clientWidth, scroll: node.scrollWidth, clientHeight: node.clientHeight, scrollHeight: node.scrollHeight }))
      assert(optionSize.scroll <= optionSize.client + 1 && optionSize.scrollHeight <= optionSize.clientHeight + 1, '候选选项完整换行')
      await option.click()
      await menu.waitFor({ state: 'hidden' })
      assert.equal(await control('第 1 行批次').locator('.ant-select-selection-item').count(), 0, '更换仓库清空原批次')
      const warehouseField = warehouse.locator('xpath=..')
      assert.equal(await warehouse.locator('.app-select__reference-name').innerText(), '成品仓 · 东莞二厂 B 区出口订单待出货产品与独立包装存放区')
      assert(!(await warehouseField.innerText()).includes('WH-SEWING-01'), '替换后不残留旧编码')
      await warehouse.locator('.ant-select-clear').click()
      assert.equal(await warehouseField.locator('.app-select__reference-code').count(), 0, '清空移除编码')
      assert.equal(await warehouse.locator('.ant-select-selection-item').count(), 0)
      await warehouse.getByRole('combobox').press('ArrowDown')
      await menu.locator('.ant-select-item-option').first().waitFor()
      assert((await menu.boundingBox()).width >= 559, '空值选择框仍提供完整宽度的候选列表')
      await warehouse.getByRole('combobox').press('Escape')
      await menu.waitFor({ state: 'hidden' })
      await sample.getByRole('button', { name: '恢复初始内容', exact: true }).click()
      await sample.getByRole('checkbox', { name: '长名称', exact: true }).uncheck()
      assert(Math.abs((await product.boundingBox()).height - normalHeight) <= 1, '短名称恢复正常高度')
      await sample.getByRole('checkbox', { name: '长名称', exact: true }).check()
      await sample.getByRole('checkbox', { name: '增加 4 列', exact: true }).check()
      await assertBusinessNoteTextAreas(sample)
      const note = sample.getByRole('textbox', { name: '第 1 行备注', exact: true })
      const initialNoteHeight = (await note.boundingBox()).height
      await note.fill('包装与分批交付要求\n'.repeat(8))
      await page.waitForFunction((height) => document.querySelector('textarea[aria-label="第 1 行备注"]').getBoundingClientRect().height > height, initialNoteHeight)
      await assertBusinessNoteTextAreas(sample)
      await note.fill('')
      await page.waitForFunction((height) => Math.abs(document.querySelector('textarea[aria-label="第 1 行备注"]').getBoundingClientRect().height - height) <= 1, initialNoteHeight)
      await sample.getByRole('checkbox', { name: '窄区域', exact: true }).check()
      await waitForFiniteAnimations(page)
      const region = sample.getByRole('region', { name: '长值演示明细', exact: true })
      const dimensions = await region.evaluate((node) => ({ client: node.clientWidth, scroll: node.scrollWidth }))
      assert(dimensions.client <= 420 && dimensions.scroll > dimensions.client, '列增加时只滚动明细容器')
      await assertSingleSelectValues(sample, '长引用十列窄区域', 6)

      const packing = control('第 1 行包装方式')
      const packingValue = await packing.locator('.ant-select-selection-item').getAttribute('title')
      assert(packingValue.includes('外箱加防护隔板与标识'), '紧凑选中值保留完整文字')
      await packing.getByRole('combobox').press('ArrowDown')
      await menu.locator('.ant-select-item-option').first().waitFor()
      assert((await menu.innerText()).includes('外箱加防护隔板与标识'), '键盘可从选项查看长值')
      const box = await menu.evaluate((node) => ({ client: node.clientWidth, scroll: node.scrollWidth, left: node.getBoundingClientRect().left, right: node.getBoundingClientRect().right }))
      assert(box.scroll <= box.client + 1 && box.left >= 0 && box.right <= 1920, '选项层不被滚动区域裁剪')
      await packing.getByRole('combobox').press('Escape')
      await menu.waitFor({ state: 'hidden' })
      assert(await packing.getByRole('combobox').evaluate((node) => node === document.activeElement), 'Escape 返回选择框')
      await sample.getByRole('checkbox', { name: '增加 4 列', exact: true }).uncheck()
      await sample.getByRole('button', { name: '恢复初始内容', exact: true }).click()
      assert.equal(await sample.getByRole('columnheader').count(), 8, '恢复六个业务列和序号、操作')
      assert.equal(await sample.getByRole('checkbox', { name: '窄区域', exact: true }).isChecked(), false)
      await assertNoHorizontalOverflow(page)
      await page.getByRole('navigation', { name: '控件设计目录', exact: true }).getByRole('button', { name: /组件选用/u }).click()
      await page.getByRole('link', { name: '操作长值与多列示例', exact: true }).click()
      await sample.waitFor()
      assert.equal(new URL(page.url()).searchParams.get('control'), 'select-overflow', '组件选用可回到正式长值样例')
    },
  }]
}
