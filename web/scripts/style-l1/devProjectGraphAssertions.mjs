export async function installIntegrationWorkspaceMock(page) {
  const snapshot = permissionRelationshipFixture()
  snapshot.permissions = [{
    permission_key: PermissionCode.SALES_ORDER_CANCEL, name: '取消销售订单',
    usage: { backend_methods: [{ domain: 'sales_order', method: RpcMethod.sales_order.CANCEL_SALES_ORDER }], conditions: ['仍受单据状态限制'] },
  }]
  await page.route(`**${DEV_PERMISSION_RELATIONSHIPS_API}`, (route) => route.fulfill({ json: snapshot }))
  await page.route('**/__dev/api/qa/quality-gates', (route) => route.fulfill({ json: createQualityGateStyleSummary() }))
}

