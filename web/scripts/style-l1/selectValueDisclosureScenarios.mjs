import { assertSingleSelectValues } from './singleSelectAssertions.mjs'
import { waitForFiniteAnimations } from './browserReadiness.mjs'

export function createSelectValueDisclosureScenarios({ assert, assertNoHorizontalOverflow }) {
  return [{
    name: 'dev-ui-select-overflow',
    path: '/__dev/ui-design?page=controls&control=select-overflow',
    viewport: { width: 1920, height: 1080 },
    verify: async (page) => {
      const sample = page.getByRole('region', { name: '长值与多列样例', exact: true })
      await sample.waitFor()
      const control = (name) => sample.getByRole('combobox', { name, exact: true }).locator('xpath=ancestor::*[contains(concat(" ", normalize-space(@class), " "), " app-select ")][1]')
      const product = control('第 1 行产品')
      const warehouse = control('第 1 行仓库')
      const productReader = product.getByRole('button', { name: '查看第 1 行产品完整值', exact: true })
      await productReader.waitFor()
      assert(await product.getByRole('combobox').isDisabled(), '导入字段保持禁用')
      const initialHeight = (await warehouse.boundingBox()).height
      await productReader.click()
      const productDialog = page.getByRole('dialog', { name: '第 1 行产品完整值', exact: true })
      await productDialog.waitFor()
      await waitForFiniteAnimations(page)
      assert(await productDialog.evaluate((node) => node === document.activeElement), '打开后焦点进入完整值浮层')
      assert((await productDialog.innerText()).includes('独立包装规格 27016-1'), '锁定字段可读取完整尾部')
      assert.equal(await page.locator('.ant-select-dropdown:visible').count(), 0, '查看完整值不会打开选项或解除锁定')
      await productDialog.press('Escape')
      await productDialog.waitFor({ state: 'hidden' })
      assert(await productReader.evaluate((node) => node === document.activeElement), 'Escape 返回查看入口')
      await productReader.press('Enter')
      await productDialog.waitFor()
      await productDialog.getByRole('button', { name: '关闭', exact: true }).click()
      assert(await productReader.evaluate((node) => node === document.activeElement), '关闭返回查看入口')
      await productReader.press('Enter')
      await productDialog.waitFor()
      await productDialog.press('Tab')
      await productDialog.getByRole('button', { name: '关闭', exact: true }).press('Tab')
      await productDialog.waitFor({ state: 'hidden' })

      await warehouse.getByRole('combobox').fill('FINISHED')
      const menu = page.locator('.ant-select-dropdown:visible')
      await menu.locator('.ant-select-item-option').first().waitFor()
      await waitForFiniteAnimations(page)
      assert((await menu.boundingBox()).width >= 320, `选项层独立于窄列展开: ${JSON.stringify(await menu.boundingBox())}`)
      await menu.getByText('成品仓 · 二楼成品待发货区（WH-FINISHED-02）', { exact: true }).click()
      await menu.waitFor({ state: 'hidden' })
      assert.equal(await control('第 1 行批次').locator('.ant-select-selection-item').count(), 0, '更换仓库清空原批次')
      assert(Math.abs((await warehouse.boundingBox()).height - initialHeight) <= 1, '选择长名称不改变高度')
      await warehouse.getByRole('button', { name: '查看第 1 行仓库完整值', exact: true }).click()
      const warehouseDialog = page.getByRole('dialog', { name: '第 1 行仓库完整值', exact: true })
      await waitForFiniteAnimations(page)
      assert(await warehouseDialog.evaluate((node) => node === document.activeElement), '可编辑字段同样将焦点交给阅读浮层')
      assert((await warehouseDialog.innerText()).includes('WH-FINISHED-02'))
      assert(!(await warehouseDialog.innerText()).includes('WH-SEWING-01'), '详情只显示当前值')
      await warehouse.locator('.ant-select-clear').click()
      await warehouseDialog.waitFor({ state: 'hidden' })
      assert.equal(await warehouse.locator('.app-select__inspect').count(), 0, '清空移除完整值入口')
      assert.equal(await warehouse.locator('.ant-select-selection-item').count(), 0)
      await sample.getByRole('button', { name: '恢复初始内容', exact: true }).click()
      await sample.getByRole('checkbox', { name: '长名称', exact: true }).uncheck()
      await productReader.waitFor({ state: 'hidden' })
      await sample.getByRole('checkbox', { name: '长名称', exact: true }).check()
      await productReader.waitFor()
      await sample.getByRole('checkbox', { name: '增加 4 列', exact: true }).check()
      await sample.getByRole('checkbox', { name: '窄区域', exact: true }).check()
      await waitForFiniteAnimations(page)
      const region = sample.getByRole('region', { name: '长值演示明细', exact: true })
      const dimensions = await region.evaluate((node) => ({ client: node.clientWidth, scroll: node.scrollWidth }))
      assert(dimensions.client <= 420 && dimensions.scroll > dimensions.client, '列增加时只滚动明细容器')
      await assertSingleSelectValues(sample, '长值演示十列窄区域', 6)
      await productReader.click()
      await productDialog.waitFor()
      const content = productDialog.locator('.app-select-value-popover__text')
      const box = await content.evaluate((node) => ({ client: node.clientWidth, scroll: node.scrollWidth, left: node.getBoundingClientRect().left, right: node.getBoundingClientRect().right }))
      assert(box.scroll <= box.client + 1 && box.left >= 0 && box.right <= 1920, '完整值在视口内换行，不被明细滚动裁剪')
      await productDialog.press('Escape')
      const packing = control('第 1 行包装方式')
      await packing.getByRole('button', { name: '查看第 1 行包装方式完整值', exact: true }).click()
      const packingDialog = page.getByRole('dialog', { name: '第 1 行包装方式完整值', exact: true })
      await packingDialog.waitFor()
      assert((await packingDialog.innerText()).includes('外箱加防护隔板与标识'), '非受控默认值同样可读取')
      await sample.getByRole('checkbox', { name: '增加 4 列', exact: true }).uncheck()
      await packingDialog.waitFor({ state: 'hidden' })
      await sample.getByRole('button', { name: '恢复初始内容', exact: true }).click()
      assert.equal(await sample.getByRole('columnheader').count(), 8, '恢复六个业务列和序号、操作')
      assert.equal(await sample.getByRole('checkbox', { name: '窄区域', exact: true }).isChecked(), false)
      await assertNoHorizontalOverflow(page)
      await page.getByRole('navigation', { name: '控件设计目录', exact: true }).getByRole('button', { name: /组件选用/u }).click()
      await page.getByRole('link', { name: '操作长值与多列示例', exact: true }).click()
      await sample.waitFor()
      assert.equal(new URL(page.url()).searchParams.get('control'), 'select-overflow', '组件选用可回到正式长值样例')
    },
  }]
}
